const CI_PACKAGE_SCRIPTS = new Set(
  QUALITY_GATES.flatMap((gate) => {
    if (gate.command === 'npm test') return ['test']
    const match = gate.command.match(/^npm run ([A-Za-z0-9:_-]+)$/)
    return match ? [match[1]] : []
  }),
)

const BUILD_PREREQ_PACKAGE_SCRIPTS = new Set([
  'bundle:check',
  'bundle:report',
  'check:pdf-lazy-entrypoints',
])

const SECRET_PREREQ_PACKAGE_SCRIPTS = new Set([
  'cleanup:runtime-fixtures',
  'cutover:preflight',
  'cutover:smoke',
  'cutover:smoke:isolation',
  'e2e:multiuser',
  'smoke:multiuser:prod',
  'smoke:production-report',
])

function packageScriptRequires(entry, commands) {
  return entry.packageScripts.some((command) => commands.has(command))
}

function scriptRunsInCi(entry) {
  if (packageScriptRequires(entry, CI_PACKAGE_SCRIPTS)) return true
  return QUALITY_GATES.some((gate) => gate.command.includes(entry.file))
}

function scriptPrerequisites(entry) {
  const prerequisites = []
  if (packageScriptRequires(entry, BUILD_PREREQ_PACKAGE_SCRIPTS))
    prerequisites.push('build')
  if (packageScriptRequires(entry, SECRET_PREREQ_PACKAGE_SCRIPTS)) {
    prerequisites.push('deploy-url', 'tokens-or-clerk')
  }
  if (entry.domain === 'database') prerequisites.push('postgres')
  return [...new Set(prerequisites)]
}

export const SCRIPT_REGISTRY = SCRIPT_ENTRIES.map((entry) => ({
  runsInCi: scriptRunsInCi(entry),
  requiresBuild: packageScriptRequires(entry, BUILD_PREREQ_PACKAGE_SCRIPTS),
  requiresSecrets: packageScriptRequires(entry, SECRET_PREREQ_PACKAGE_SCRIPTS),
  prerequisites: scriptPrerequisites(entry),
  risk: entry.critical ? 'blocking' : 'advisory',
  ...entry,
}))
